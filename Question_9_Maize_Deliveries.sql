CREATE OR REPLACE FUNCTION fn_maize_rate(p_grade CHAR)
RETURNS NUMERIC(8,2) LANGUAGE plpgsql AS $$
BEGIN
 IF p_grade IS NULL OR UPPER(p_grade) NOT IN ('A','B','C') THEN
   RAISE EXCEPTION 'Grade must be A, B or C';
 END IF;
 RETURN CASE UPPER(p_grade) WHEN 'A' THEN 5.00 WHEN 'B' THEN 4.00 ELSE 3.00 END;
END $$;

CREATE OR REPLACE FUNCTION trg_price_delivery()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.weight_kg IS NULL OR NEW.weight_kg<=0 THEN
   RAISE EXCEPTION 'Delivery weight must be greater than zero';
 END IF;
 NEW.grade:=UPPER(NEW.grade);
 NEW.unit_rate:=fn_maize_rate(NEW.grade);
 NEW.total_value:=NEW.weight_kg*NEW.unit_rate;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_delivery_price
BEFORE INSERT OR UPDATE ON deliveries
FOR EACH ROW EXECUTE FUNCTION trg_price_delivery();

CREATE OR REPLACE PROCEDURE pr_receive_delivery(
 p_farmer_id INT,p_grade CHAR,p_weight NUMERIC,p_date DATE)
LANGUAGE plpgsql AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM farmers WHERE farmer_id=p_farmer_id) THEN
   RAISE EXCEPTION 'Unknown farmer ID: %',p_farmer_id;
 END IF;
 IF p_weight IS NULL OR p_weight<=0 OR p_date IS NULL THEN
   RAISE EXCEPTION 'Weight must be positive and delivery date is required';
 END IF;
 PERFORM fn_maize_rate(p_grade);
 INSERT INTO deliveries(farmer_id,grade,weight_kg,delivered_on,is_paid)
 VALUES(p_farmer_id,UPPER(p_grade),p_weight,p_date,FALSE);
 -- Trigger supplies unit_rate and total_value.
END $$;

CREATE OR REPLACE VIEW v_farmer_amount_due AS
SELECT f.farmer_number,f.full_name,
       COALESCE(SUM(d.total_value) FILTER(WHERE d.is_paid=FALSE),0)::NUMERIC(14,2) AS amount_due
FROM farmers f LEFT JOIN deliveries d ON d.farmer_id=f.farmer_id
GROUP BY f.farmer_id,f.farmer_number,f.full_name;

CREATE INDEX idx_deliveries_farmer_date ON deliveries(farmer_id,delivered_on);
EXPLAIN SELECT delivery_id,grade,weight_kg,total_value
FROM deliveries WHERE farmer_id=1
AND delivered_on BETWEEN CURRENT_DATE-30 AND CURRENT_DATE;

CREATE OR REPLACE PROCEDURE pr_refresh_purchases(p_day DATE)
LANGUAGE plpgsql AS $$
BEGIN
 IF p_day IS NULL THEN RAISE EXCEPTION 'Purchase date cannot be NULL'; END IF;
 INSERT INTO daily_purchases(purchase_date,total_weight,total_value)
 SELECT p_day,COALESCE(SUM(weight_kg),0),COALESCE(SUM(total_value),0)
 FROM deliveries WHERE delivered_on=p_day
 ON CONFLICT(purchase_date) DO UPDATE SET
 total_weight=EXCLUDED.total_weight,total_value=EXCLUDED.total_value;
END $$;

