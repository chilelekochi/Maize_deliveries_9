CREATE SCHEMA IF NOT EXISTS q9_maize;
SET search_path TO q9_maize, public;

DROP VIEW IF EXISTS v_farmer_amount_due;
DROP TABLE IF EXISTS daily_purchases,deliveries,farmers CASCADE;
DROP FUNCTION IF EXISTS fn_maize_rate(CHAR);
DROP PROCEDURE IF EXISTS pr_receive_delivery(INT,CHAR,NUMERIC,DATE);
DROP PROCEDURE IF EXISTS pr_refresh_purchases(DATE);

CREATE TABLE farmers (
 farmer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 farmer_number VARCHAR(20) NOT NULL UNIQUE,
 full_name VARCHAR(120) NOT NULL
);
CREATE TABLE deliveries (
 delivery_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 farmer_id INT NOT NULL REFERENCES farmers(farmer_id),
 grade CHAR(1) NOT NULL CHECK(grade IN ('A','B','C')),
 weight_kg NUMERIC(12,2) NOT NULL CHECK(weight_kg>0),
 unit_rate NUMERIC(8,2) NOT NULL DEFAULT 0,
 total_value NUMERIC(14,2) NOT NULL DEFAULT 0,
 delivered_on DATE NOT NULL,
 is_paid BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE daily_purchases (
 purchase_date DATE PRIMARY KEY,
 total_weight NUMERIC(14,2) NOT NULL,
 total_value NUMERIC(14,2) NOT NULL
);
